// Shared driver of the expected-density tools (one binary per app, see Makefile).
//
// The expected density of a scheme is the limit of its particular density on a
// uniformly random string. Each tool estimates it on N random bases, cut into
// independent sequences ("chunks") of C bases, and counts the selected k-mers
// with the app's own selection code (the backend), exactly as the app counts
// them for its particular density, so that the expected and particular values
// are on the same scale and follow the app's tie-breaking rule by construction:
//
//   kraken2   MinimizerScanner::NextMinimizer, a new minimizer value (build_db)
//   minimap2  mm_sketch / mm_sketch_scheme entries (the index's minimizers)
//   kmc       CSplitter::ProcessReadsT superwindows (PutExtendedKmer calls)
//   sshash    compute_minimizer_tuples super-k-mers (a new minimizer position)
//
// A backend is a class with
//   explicit Backend(const Args &);           // parses its own options from Args
//   void count(const char *seq, size_t len, uint64_t &n_kmers, uint64_t &n_selected);
// where seq is ACGT text (upper case) and n_kmers is the app's own count of
// k-mers of seq (after homopolymer compression where the app applies it).
// One Backend instance is made per thread.
//
// Random string: chunk c of seed s is generated by xoshiro256** seeded with
// splitmix64 from (s, c), two bits per base, so each seed has its own string and
// the result does not depend on the number of threads. A chunk boundary only
// charges the first window of the chunk: with C = 10^7 bases the bias of the
// density is below 10^-6 relative.
//
// Output: one CSV line per seed on stdout,
//   seed,n_bases,chunk_bases,n_kmers,n_selected,density_factor
// With --fasta FILE the tool instead counts the sequences of FILE (validation
// against the app's own binary on the same input) and prints one line with
// seed "fasta".

